    /** @return array<string, mixed> */
    public static function get(string $key): array
    {
        $pillar = self::all()[$key] ?? null;

        if ($pillar === null) {
            throw new InvalidArgumentException("Unknown SEO Pillar [{$key}].");
        }

        return $pillar;
    }

    /** @return array<int, string> */
    public static function paths(): array
    {
        return array_values(array_map(
            static fn (array $pillar): string => $pillar['path'],
            self::all(),
        ));
    }
